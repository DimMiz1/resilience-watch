import math


def train_logistic(rows, labels, epochs=300, lr=0.1, l2=0.001):
    """
    Train binary logistic regression with full-batch gradient descent.
    
    Args:
        rows: list of equal-length lists of floats
        labels: list of 0/1 ints
        epochs: number of training epochs
        lr: learning rate
        l2: L2 regularization strength (applied to weights, not bias)
    
    Returns:
        dict with keys 'mean', 'std', 'weights', 'bias'
    """
    if not rows:
        raise ValueError("rows is empty")
    
    n_samples = len(rows)
    n_features = len(rows[0])
    
    # Check all rows have same length
    for i, row in enumerate(rows):
        if len(row) != n_features:
            raise ValueError(f"Row {i} has length {len(row)}, expected {n_features}")
    
    # Check labels length
    if len(labels) != n_samples:
        raise ValueError(f"labels length {len(labels)} does not match rows length {n_samples}")
    
    # Check labels contain both classes
    unique_labels = set(labels)
    if len(unique_labels) < 2:
        raise ValueError("labels contain only one class")
    
    # Standardize features using population statistics
    means = []
    stds = []
    for j in range(n_features):
        col = [rows[i][j] for i in range(n_samples)]
        mean = sum(col) / n_samples
        variance = sum((x - mean) ** 2 for x in col) / n_samples
        std = math.sqrt(variance) if variance > 0 else 1.0
        if std == 0:
            std = 1.0
        means.append(mean)
        stds.append(std)
    
    # Standardize the data
    standardized_rows = []
    for row in rows:
        std_row = [(row[j] - means[j]) / stds[j] for j in range(n_features)]
        standardized_rows.append(std_row)
    
    # Compute class weights
    n_pos = sum(labels)
    n_neg = n_samples - n_pos
    if n_pos == 0 or n_neg == 0:
        raise ValueError("labels contain only one class")
    
    weight_pos = n_neg / n_pos
    weight_neg = 1.0
    
    # Initialize weights and bias
    weights = [0.0] * n_features
    bias = 0.0
    
    # Numerically stable sigmoid
    def sigmoid(z):
        if z >= 0:
            return 1.0 / (1.0 + math.exp(-z))
        else:
            ez = math.exp(z)
            return ez / (1.0 + ez)
    
    # Training loop
    for epoch in range(epochs):
        # Compute predictions for all samples
        predictions = []
        for i in range(n_samples):
            z = bias + sum(weights[j] * standardized_rows[i][j] for j in range(n_features))
            p = sigmoid(z)
            predictions.append(p)
        
        # Compute gradients
        grad_weights = [0.0] * n_features
        grad_bias = 0.0
        
        for i in range(n_samples):
            y = labels[i]
            p = predictions[i]
            error = p - y
            
            # Weight the error by class weight
            if y == 1:
                weighted_error = error * weight_pos
            else:
                weighted_error = error * weight_neg
            
            grad_bias += weighted_error
            for j in range(n_features):
                grad_weights[j] += weighted_error * standardized_rows[i][j]
        
        # Average gradients
        grad_bias /= n_samples
        for j in range(n_features):
            grad_weights[j] /= n_samples
        
        # Add L2 regularization gradient (only for weights, not bias)
        for j in range(n_features):
            grad_weights[j] += l2 * weights[j]
        
        # Update weights and bias
        bias -= lr * grad_bias
        for j in range(n_features):
            weights[j] -= lr * grad_weights[j]
    
    return {
        'mean': means,
        'std': stds,
        'weights': weights,
        'bias': bias
    }


def roc_auc(labels, scores):
    """
    Compute the area under the ROC curve for binary labels (0/1) and float scores.
    
    Uses the Mann-Whitney U statistic approach where tied scores get their average rank.
    
    Args:
        labels: List of binary labels (0 or 1)
        scores: List of float scores
    
    Returns:
        Float representing the AUC
    
    Raises:
        ValueError: If lengths differ, input is empty, or only one class is present
    """
    if len(labels) != len(scores):
        raise ValueError("Labels and scores must have the same length")
    
    if len(labels) == 0:
        raise ValueError("Input is empty")
    
    n_pos = sum(labels)
    n_neg = len(labels) - n_pos
    
    if n_pos == 0 or n_neg == 0:
        raise ValueError("Only one class is present")
    
    # Create pairs of (score, label)
    pairs = list(zip(scores, labels))
    
    # Sort by score ascending, then by label descending (to handle ties consistently)
    # For average rank: we need to assign ranks to all items, where tied scores get average rank
    # Sort by score ascending
    sorted_pairs = sorted(pairs, key=lambda x: (x[0], -x[1]))
    
    n = len(sorted_pairs)
    
    # Assign ranks with average for ties
    ranks = [0.0] * n
    i = 0
    while i < n:
        j = i
        # Find all items with the same score
        while j < n and sorted_pairs[j][0] == sorted_pairs[i][0]:
            j += 1
        # Items from i to j-1 have the same score
        # Their ranks would be i+1, i+2, ..., j
        # Average rank is (i+1 + j) / 2
        avg_rank = (i + 1 + j) / 2.0
        for k in range(i, j):
            ranks[k] = avg_rank
        i = j
    
    # Extract ranks for positive and negative classes
    # We need to map back to original order? No, we just need the sum of ranks for positives
    # The pairs are sorted, but we need to know which ones are positive
    pos_ranks = []
    neg_ranks = []
    for idx, (score, label) in enumerate(sorted_pairs):
        if label == 1:
            pos_ranks.append(ranks[idx])
        else:
            neg_ranks.append(ranks[idx])
    
    # Mann-Whitney U statistic
    # U1 = sum of ranks for positives - n_pos*(n_pos+1)/2
    sum_pos_ranks = sum(pos_ranks)
    U1 = sum_pos_ranks - n_pos * (n_pos + 1) / 2.0
    
    # AUC = U1 / (n_pos * n_neg)
    auc = U1 / (n_pos * n_neg)
    
    return auc


def predict_proba(model, row):
    """Logistic score for a raw row; undo class weighting when that metadata exists."""
    if len(row) != len(model["weights"]) or not all(math.isfinite(x) for x in row):
        raise ValueError("Prediction needs one finite value per feature.")
    z = model["bias"] + sum(w * (x - m) / s for w, x, m, s in zip(model["weights"], row, model["mean"], model["std"]))
    z -= math.log(model.get("positive_class_weight", 1.0))
    return 1.0 / (1.0 + math.exp(-z)) if z >= 0 else math.exp(z) / (1.0 + math.exp(z))
